// Fetch formulas and charges for the engine's species from BiGG (King et al.
// 2015), as the E. coli model iJO1366 has them (one consistent protonation
// at pH 7.2), and write src/engine/formulas.js, so the balance tests check
// reactions against an independent source. The protein carriers (plastocyanin
// and cytochrome c, ferredoxin) and photons aren't small molecules; their
// forms are written by hand in src/engine/species.js.
// usage: node tools/bigg.mjs
import { writeFile } from 'node:fs/promises';

const IDS = [
    'atp', 'adp', 'amp', 'pi', 'ppi', 'h2o', 'h', 'co2', 'o2', 'nad', 'nadh', 'nadp', 'nadph',
    'coa', 'accoa', 'malcoa', 'succoa', 'glc__D', 'g6p', 'f6p', 'fdp', 'g3p', '13dpg', '3pg', '2pg', 'pep', 'pyr',
    'lac__L', 'lac__D', 'acald', 'etoh', 'ac', 'oaa', 'cit', 'icit', 'akg', 'succ', 'fum', 'mal__L',
    '6pgl', '6pgc', 'ru5p__D', 'r5p', 'xu5p__D', 'e4p', 's7p', 's17bp', 'rb15bp',
    'q8', 'q8h2', 'hco3', 'hdca', 'o2s', 'h2o2', 'k',
    'pmtcoa', 'tdcoa', 'ddcacoa', 'dcacoa', 'occoa', 'hxcoa', 'btcoa',
    'hdd2coa', 'td2coa', 'dd2coa', 'dc2coa', 'oc2coa', 'hx2coa', 'b2coa',
    '3hhdcoa', '3htdcoa', '3hddcoa', '3hdcoa', '3hocoa', '3hhcoa', '3hbcoa',
    '3ohdcoa', '3otdcoa', '3oddcoa', '3odcoa', '3oocoa', '3ohcoa', 'aacoa',
];

const out = {};
for (const id of IDS) {
    // RuBP isn't in E. coli: those come from the Synechocystis model, iJN678
    let r, model;
    for (model of ['iJO1366', 'iJN678']) { r = await fetch(`https://bigg.ucsd.edu/api/v2/models/${model}/metabolites/${id}_c`); if (r.ok) break; }
    if (!r.ok) { console.error('missing', id, r.status); continue; }
    const d = await r.json();
    out[id] = [d.formula, d.charge, d.name + (model === 'iJO1366' ? '' : ' (' + model + ')')];
}
const rows = Object.entries(out).map(([id, v]) => `    ${JSON.stringify(id)}: ${JSON.stringify(v)},`).join('\n');
const body = `// Generated by tools/bigg.mjs from BiGG (bigg.ucsd.edu; King et al. 2015,
// 10.1093/nar/gkv1049), model iJO1366 (iJN678 where E. coli lacks one), on ${new Date().toISOString().slice(0, 10)}. Do not edit: these
// formulas and charges are the independent reference the balance tests check
// reactions against. id → [formula, charge at pH 7.2, BiGG's name]
export const FORMULAS = {
${rows}
};
`;
await writeFile(new URL('../src/engine/formulas.js', import.meta.url), body);
console.log(Object.keys(out).length, 'of', IDS.length);
